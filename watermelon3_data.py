WATERMELON_COLUMNS: tuple[str, ...] = (
    "编号", "色泽", "根蒂", "敲声", "纹理", "脐部", "触感", "密度", "含糖率", "好瓜",
)

#: 各离散字段的合法取值集合，供校验脚本做集合断言
DISCRETE_DOMAINS: dict[str, set[str]] = {
    "色泽": {"青绿", "乌黑", "浅白"},
    "根蒂": {"蜷缩", "稍蜷", "硬挺"},
    "敲声": {"浊响", "沉闷", "清脆"},
    "纹理": {"清晰", "稍糊", "模糊"},
    "脐部": {"凹陷", "稍凹", "平坦"},
    "触感": {"硬滑", "软粘"},
    "好瓜": {"是", "否"},
}


def load_watermelon3() -> pd.DataFrame:
    """返回西瓜数据集 3.0 的 DataFrame（dtype 与教材一致）。"""
    df = pd.DataFrame(WATERMELON_3_0_ROWS, columns=list(WATERMELON_COLUMNS))
    # 显式指定 dtype：编号 int，密度/含糖率 float，其余 object（中文不转 categorical，
    # 避免 to_csv 时被自动改写）
    df = df.astype({
        "编号": "int64",
        "色泽": "object", "根蒂": "object", "敲声": "object",
        "纹理": "object", "脐部": "object", "触感": "object",
        "密度": "float64", "含糖率": "float64",
        "好瓜": "object",
    })
    return df


def _self_check() -> None:
    """模块级自检：转录错误在这里就该崩，而不是等到 CSV 落盘之后。

    运行方式：``python watermelon3_data.py``
    """
    df = load_watermelon3()

    assert df.shape == (17, 10), f"形状应为 (17, 10)，实际 {df.shape}"
    assert list(df.columns) == list(WATERMELON_COLUMNS), "列名与原表不一致"
    assert df["编号"].tolist() == list(range(1, 18)), "编号应连续 1–17"
    assert df.isna().sum().sum() == 0, "教材原表无缺失值"

    for col, domain in DISCRETE_DOMAINS.items():
        actual = set(df[col])
        assert actual <= domain, f"{col} 出现非法取值：{sorted(actual - domain)}"

    # 类别分布：教材 3.0 为 8 好瓜 / 9 否
    vc = df["好瓜"].value_counts()
    assert vc["是"] == 8 and vc["否"] == 9, f"好瓜分布应为 8/9，实际 {vc.to_dict()}"

    # 两列连续属性的取值范围（教材实际取值）
    assert df["密度"].between(0, 1).all(), "密度应在 (0, 1)"
    assert df["含糖率"].between(0, 1).all(), "含糖率应在 (0, 1)"
    assert df["密度"].min() == 0.243 and df["密度"].max() == 0.774
    assert df["含糖率"].min() == 0.042 and df["含糖率"].max() == 0.460

    # 离散属性必须仍是字符串，未被编码为数字（作业第 6 节验收原文）
    assert df["色泽"].dtype == object, "色泽不应是数值类型"

    print("西瓜数据集 3.0 自检通过：")
    print(df.head(3).to_string(index=False))
    print(f"  ... 共 {len(df)} 行，好瓜 {vc['是']} / 否 {vc['否']}")
    print(f"  密度 {df['密度'].min():.3f}–{df['密度'].max():.3f}，"
          f"含糖率 {df['含糖率'].min():.3f}–{df['含糖率'].max():.3f}")


if __name__ == "__main__":
    _self_check()
