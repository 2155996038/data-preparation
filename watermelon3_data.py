"""西瓜数据集 3.0（内嵌常量）。

来源
----
周志华《机器学习》，清华大学出版社，2016 年 1 月第 1 版。
数据见该书附录"西瓜数据集"，编号 3.0 的版本共 17 个样本、9 个字段。

为什么内嵌而不是下载
--------------------
该数据集是教材附录中的一张小表，**没有官方公开下载地址**。网上流传的多个
CSV 副本在字段名、取值写法（如"青绿"vs"青绿 "）、小数位数上互不一致，
直接引用会造成"同学间数据不一致"（正是作业第 10 节要求规避的问题）。
因此这里把教材原表逐行转录为常量，并在 ``validate_data.py`` 中用硬断言
锁定行数、类别取值集合与两列的数值范围，确保任何转录错误都会立刻暴露。

版本区分（作业第 6 节要求"版本明确"）
--------------------------------------
- **2.0**：17 个样本，只有 6 个离散属性，**无**密度与含糖率；
- **3.0**：17 个样本，在 2.0 基础上**增加**密度、含糖率两个连续属性 ← 本文件
- **4.0**：17 个样本，离散属性改为"色泽/根蒂/敲声/纹理/脐部/触感"，
  并把纹理改成三种取值（清晰/稍糊/模糊）；**含糖率替换为含糖率的不同定义**，
  标签写法为"是/否"。若后续课程用到 4.0，请另存为 ``watermelon4.0.csv``，
  不得覆盖本文件。

字段
----
编号      样本序号 1–17（教材原表有，故保留）
色泽/根蒂/敲声/纹理/脐部/触感   6 个中文离散属性，**保持字符串，不编码为数字**
密度/含糖率                     2 个连续属性，保留教材原始 3 位小数
好瓜                           标签，"是" / "否"
"""

